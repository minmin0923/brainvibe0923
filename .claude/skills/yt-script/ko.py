"""ko.py - 한국어 처리 공용 모듈. yt-* 스크립트들이 같이 쓴다.

원본 스크립트는 영어 정규식([a-z]+)만 써서 한글을 아예 읽지 못했다. 여기서는
  - 한글 낱말을 토큰으로 인식하고, 끝에 붙은 조사(은/는/이/가/을/를...)를 떼어 비교한다.
  - 한국어 과장어, 군말, 시청자 호칭, 손해·위험 표현, 궁금증 표현 목록을 둔다.
  - 한글은 영문보다 화면 폭이 넓으므로 제목 잘림 판단에 '표시 폭'을 쓴다.
목록은 경험칙이다. 점수는 다시 볼 이유이지 성과 예측이 아니다.
"""
import re

HANGUL = re.compile(r"[가-힣]")
TOKEN = re.compile(r"[a-z0-9'%$.]+|[가-힣]+", re.I)

# 긴 것부터 떼어야 '으로'가 '로'보다 먼저 맞는다.
PARTICLES = sorted(("은 는 이 가 을 를 에 의 도 로 으로 와 과 에서 까지 만 부터 보다 처럼 "
                    "이랑 랑 하고 에게 한테 께 이나 나 이란 란 라는 이라는 으로는 에서는 에는").split(),
                   key=len, reverse=True)

def is_ko(text):
    return len(HANGUL.findall(text)) >= 2

def strip_particle(w):
    if not w or not HANGUL.match(w[-1]):
        return w
    # '앱을', '책은' 처럼 한 글자 명사 + 을/를/은/는 은 뗀다('사이', '평가'는 이 조사로 안 끝나서 안전)
    if len(w) == 2 and w[1] in "을를은는":
        return w[0]
    for p in PARTICLES:
        # 두 글자 낱말(평가, 사이)은 건드리지 않는다. 조사를 떼고도 두 글자 이상 남을 때만 뗀다.
        if len(w) - len(p) >= 2 and w.endswith(p):
            return w[:-len(p)]
    return w

def tokens(text):
    return [strip_particle(w.lower()) for w in TOKEN.findall(text)]

def is_wide(c):
    return ("가" <= c <= "힣" or "ᄀ" <= c <= "ᇿ" or "㄰" <= c <= "㆏"
            or "　" <= c <= "鿿" or "＀" <= c <= "￯")

def width(text):
    """영문 한 글자를 1로 볼 때의 대략적인 화면 폭. 한글은 약 1.7배 넓다(추정치)."""
    return round(sum(1.7 if is_wide(c) else 1 for c in text), 1)

def syllables(text):
    """말하는 길이를 재는 단위: 공백과 문장부호를 뺀 한글·영숫자 글자 수."""
    return len(re.findall(r"[가-힣a-zA-Z0-9]", text))

# 숫자 + 단위. '3시간', '10분', '100배', '1,000명', '30%' 같은 구체적인 수치.
CONCRETE_KO = re.compile(r"\d[\d,.]*\s?(%|퍼센트|초|분|시간|일|주|주일|개월|달|년|배|명|개|가지|"
                         r"단계|번|회|만|억|천|원|달러|건|편|줄|살|위)?")

# 과장어: 숫자·이름·날짜로 바꿔야 할 말. 부분 일치로 찾는다('완벽한', '완벽정리' 모두 잡힘).
VAGUE_KO = ["최고", "최강", "끝판왕", "완벽", "대박", "미친", "미쳤", "역대급", "레전드", "충격",
            "놀라운", "엄청난", "어마어마", "혁명", "혁신적", "꿀팁", "무조건", "사기급", "소름",
            "끝장", "개쩌", "모든 것", "모든것", "필수템", "갓성비", "신세계", "게임체인저"]

# 훅 첫머리의 군말: 정보 없이 시간만 쓰는 말.
FILLER_KO = ["여러분 안녕하세요", "안녕하세요", "오늘은", "오늘", "영상", "구독", "좋아요", "채널",
             "그냥", "진짜", "정말", "약간", "뭔가", "일단", "자 ", "네 ", "반갑습니다"]

# 제목 첫 세 낱말에 이것만 있으면 주제가 뒤로 밀린 것이다.
STOP_KO = {"이", "그", "저", "이것", "이거", "그거", "진짜", "정말", "오늘", "여러분", "드디어",
           "이번", "그냥", "모든", "완전", "결국", "요즘", "지금", "솔직히", "와", "헐"}

# 시청자를 직접 부르는 말. '비개발자라면', '초보자분들' 처럼 대상을 지목하는 말도 포함한다.
YOU_KO = re.compile(r"(여러분|당신|너희|님들|본인|구독자님|사장님|선생님|너도|너는|네가|"
                    r"[가-힣]{2,}(이라면|라면|분들|하시는 분|인 분))")
STAKE_KO = re.compile(r"(손해|낭비|버리|버려|잃|망하|망한|실패|포기|그만|비용|위험|후회|놓치|늦기|"
                      r"늦어|함정|날리|날린|돈 ?(이|을)? ?(새|버)|전에|절대|안 하면|모르면)")
CURIOSITY_KO = re.compile(r"(왜|어떻게|무엇|뭐가|무슨|어떤|아무도|몰랐|모르는|하지만|그런데|근데|"
                          r"결국|사실은|사실|의외|이유|비밀|정체|진짜 (이유|문제)|단 하나|딱 하나)")
CLOSED_KO = re.compile(r"(때문에|그래서|즉,|즉 |라서 )")

# 제목이 소리치는지: 한국어에는 대문자가 없으므로 느낌표·물음표 남발, ㅋㅋ·ㄷㄷ, 【】로 본다.
SHOUT_KO = re.compile(r"([!?]{2,}|ㅋㅋ|ㄷㄷ|ㅎㅎ|ㅠㅠ|【|】)")

# 대본·자막의 군말 덩어리(편집 목록용).
FILLER_CUE_KO = (r"음+|어+|아+|그+|에+|저기|그러니까|뭐지|뭐랄까|이제|약간|그래서|네|자|일단|아무튼|"
                 r"어쨌든|뭐|좀|막|그니까|있잖아요|그런|저|아니")


def classify(text, formulas):
    """훅 공식 분류. 영어 패턴(match)과 한국어 패턴(match_ko)을 둘 다 본다."""
    best, hits = None, 0
    for f in formulas:
        n = sum(1 for p in f.get("match", []) if re.search(p, text, re.I))
        n += sum(1 for p in f.get("match_ko", []) if re.search(p, text, re.I))
        if n > hits:
            best, hits = f, n
    return best, hits
