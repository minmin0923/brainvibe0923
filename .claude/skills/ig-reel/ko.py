def parse_count(s):
    """'412,000' '41.2만' '1.2천' '3억' '12K' '1.5M' -> 정수. 못 읽으면 None."""
    if s is None:
        return None
    t = str(s).strip().replace(",", "").replace(" ", "").replace("회", "").replace("명", "")
    if not t:
        return None
    m = re.match(r"^(\d+(?:\.\d+)?)(만|천|억|k|K|m|M|b|B)?$", t)
    if not m:
        digits = re.sub(r"[^\d]", "", t)
        return int(digits) if digits else None
    n = float(m.group(1))
    mult = {"만": 1e4, "천": 1e3, "억": 1e8, "k": 1e3, "K": 1e3, "m": 1e6, "M": 1e6,
            "b": 1e9, "B": 1e9}.get(m.group(2), 1)
    return int(round(n * mult))
