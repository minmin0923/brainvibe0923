def is_ko(text):
    return len(HANGUL.findall(text or "")) >= 2


def strip_particle(w):
    if not w or not HANGUL.match(w[-1]):
        return w
    if len(w) == 2 and w[1] in "을를은는":          # '앱을' -> '앱'
        return w[0]
    for p in PARTICLES:
        if len(w) - len(p) >= 2 and w.endswith(p):
            return w[:-len(p)]
    return w


def tokens(text):
    return [strip_particle(w.lower()) for w in TOKEN.findall(re.sub(r"(?<=\d),(?=\d)", "", text))]


def eojeol(text):
    """공백으로 나눈 어절. 한국어에서 '몇 번째 낱말' 은 어절 기준이 자연스럽다."""
    return [w for w in re.split(r"\s+", text.strip()) if w]


def syllables(text):
    """말하는 길이: 공백·문장부호를 뺀 한글·영숫자 글자 수."""
    return len(re.findall(r"[가-힣A-Za-z0-9]", text))


def is_wide(c):
    return ("가" <= c <= "힣" or "ᄀ" <= c <= "ᇿ" or "㄰" <= c <= "㆏"
            or "　" <= c <= "鿿" or "＀" <= c <= "￯"
            or "\U0001F300" <= c <= "\U0001FAFF" or "☀" <= c <= "➿")   # 이모지


def width(text):
    """영문 한 글자를 1로 볼 때의 화면 폭. 한글은 약 1.7배 넓다(추정치)."""
    return sum(1.7 if is_wide(c) else 1 for c in text)


def cut_by_width(text, limit):
    out, w = "", 0.0
    for c in text:
        w += 1.7 if is_wide(c) else 1
        if w > limit:
            break
        out += c
    return out


